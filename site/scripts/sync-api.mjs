/**
 * Copies the language server's generated builtin-API artifacts into the site's apiSource folder.
 *
 * The two used to be maintained as independent copies, which drifted: both claimed revision 32 and
 * the bytes differed. They live in one repository, so there is no reason for a second source of
 * truth — `server/src/GSCode.Workspace/Api/` is it, and this script carries it across.
 *
 * Run it after regenerating with `server/tools/field-data`, then commit the result. The copies stay
 * committed so a site build never needs the server tree present.
 *
 * Usage:  npm run sync:api        (from site/)
 *         npm run sync:api -- --check   exits non-zero if anything is out of date
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../server/src/GSCode.Workspace/Api');
const destination = resolve(here, '../src/lib/apiSource');

/** Only the function libraries. Object fields and Radiant keys are not rendered by the site yet. */
const pattern = /^[a-z0-9]+_api_(gsc|csc)\.json$/;

const checkOnly = process.argv.includes('--check');

let files;
try {
	files = readdirSync(source)
		.filter((name) => pattern.test(name))
		.sort();
} catch {
	console.error(`Could not read ${source}. Run this from a full checkout of the gscode repo.`);
	process.exit(1);
}

if (files.length === 0) {
	console.error(`No API artifacts found in ${source}.`);
	process.exit(1);
}

mkdirSync(destination, { recursive: true });

const stale = [];
for (const name of files) {
	const from = readFileSync(join(source, name));
	const to = join(destination, name);

	let existing = null;
	try {
		existing = readFileSync(to);
	} catch {
		/* not there yet */
	}

	if (existing !== null && existing.equals(from)) {
		continue;
	}

	stale.push(name);
	if (!checkOnly) {
		writeFileSync(to, from);
	}
}

// The home page states how many engine functions ship with the extension, per game. Counting them
// here rather than typing them into a component is the only way that number stays true: a
// regeneration moves it, and nobody would think to go and edit the splash.
const counts = {};
for (const name of files) {
	const [prefix, , language] = name.replace(/\.json$/, '').split('_');
	const document = JSON.parse(readFileSync(join(source, name), 'utf8'));
	const total = Array.isArray(document.api) ? document.api.length : 0;

	counts[prefix] ??= { gsc: 0, csc: 0 };
	counts[prefix][language] = total;
}

const generated = `// GENERATED by scripts/sync-api.mjs — do not edit. Run \`npm run sync:api\`.
//
// How many entries each bundled library holds, counted from the artifacts themselves. The home
// page's engine index reads these, so the figure it shows moves when the data does.

export type LibraryCount = { gsc: number; csc: number };

export const libraryCounts: Record<string, LibraryCount> = ${JSON.stringify(counts, null, '\t')};

/** Every entry across every game and both script VMs. */
export const totalBuiltins = ${Object.values(counts).reduce((sum, game) => sum + game.gsc + game.csc, 0)};
`.replace(/\r?\n/g, '\n');

const countsPath = resolve(here, '../src/lib/data/libraryCounts.ts');
let existingCounts = null;
try {
	existingCounts = readFileSync(countsPath, 'utf8').replace(/\r?\n/g, '\n');
} catch {
	/* not there yet */
}

if (existingCounts !== generated) {
	stale.push('libraryCounts.ts');
	if (!checkOnly) {
		writeFileSync(countsPath, generated);
	}
}

if (checkOnly) {
	if (stale.length > 0) {
		console.error(`Out of date with the server artifacts: ${stale.join(', ')}`);
		console.error('Run `npm run sync:api` and commit the result.');
		process.exit(1);
	}
	console.log(`All ${files.length} API artifacts are in step with the server.`);
} else {
	console.log(
		stale.length === 0
			? `All ${files.length} API artifacts were already in step.`
			: `Updated ${stale.length}: ${stale.join(', ')}`
	);
}
