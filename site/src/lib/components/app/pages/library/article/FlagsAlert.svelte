<script lang="ts">
	import BadgeCheck from '@lucide/svelte/icons/badge-check';
	import EyeOff from '@lucide/svelte/icons/eye-off';
	import MessageCircleQuestion from '@lucide/svelte/icons/message-circle-question';
	import BookOpenText from '@lucide/svelte/icons/book-open-text';
	import SquareCode from '@lucide/svelte/icons/square-code';
	import Sparkles from '@lucide/svelte/icons/sparkles';
	import PencilLine from '@lucide/svelte/icons/pencil-line';
	import FileText from '@lucide/svelte/icons/file-text';
	import TriangleAlert from '@lucide/svelte/icons/triangle-alert';
	import FlagAlert from './FlagAlert.svelte';

	interface Props {
		flags: string[];
		/**
		 * The game this library borrows its entries from, when it does. `documented` on an inheriting
		 * game means the SIBLING documents the name — World at War shipped no documentation of its
		 * own — so saying "the game's own documentation" there would contradict the library banner
		 * directly above it.
		 */
		inheritsFrom?: string | null;
		class?: string;
	}

	let { flags = [], inheritsFrom = null, class: className = '' }: Props = $props();

	/**
	 * Two vocabularies meet here.
	 *
	 * Black Ops III's library was built by a community pipeline and marks entries `processed` /
	 * `verified` / `unlisted`. The four pre-BO3 libraries come from `tools/field-data` and mark them
	 * `documented` / `aiGenerated` / `corrected` — each carrying real evidence about where the entry
	 * came from. Both sets are shown, because both describe entries this site serves.
	 */
	const known = [
		'autogenerated',
		'processed',
		'verified',
		'unlisted',
		'devblock',
		'documented',
		'aiGenerated',
		'corrected',
		'Broken'
	];

	const shown = $derived(flags.some((flag) => known.includes(flag)));
</script>

{#if shown}
	<div class="flex flex-col gap-3 {className}">
		{#if flags.includes('documented')}
			<FlagAlert
				Icon={FileText}
				title={inheritsFrom ? 'Documented elsewhere' : 'Documented'}
				description={inheritsFrom
					? `This entry is documented for ${inheritsFrom}, and carried across because the two games share the function. The description and parameters are that game's, not this one's.`
					: "This entry comes from the game's own per-function documentation, so its signature is stated by the source rather than inferred."}
			/>
		{/if}

		{#if flags.includes('aiGenerated')}
			<FlagAlert
				Icon={Sparkles}
				title="Reconstructed"
				description="No documentation covers this function. Its entry was carried over from another game that documents the same name, or rebuilt from the way the game's own scripts call it — parameter names are the callers' words. See the remarks below for what the reconstruction rests on."
			/>
		{/if}

		{#if flags.includes('corrected')}
			<FlagAlert
				Icon={PencilLine}
				title="Corrected"
				description="The documentation states this function's signature incorrectly, and a curated override has been applied over it. The correction and its reason are recorded in the generator's source."
			/>
		{/if}

		{#if flags.includes('autogenerated')}
			<FlagAlert
				Icon={MessageCircleQuestion}
				title="Unverified"
				description="This function's documentation was auto-generated from Treyarch's API, which is known to contain errors."
			/>
		{/if}

		{#if flags.includes('processed')}
			<FlagAlert
				Icon={BookOpenText}
				title="Generated"
				description="This function's documentation was batch-processed and may contain inaccuracies."
			/>
		{/if}

		{#if flags.includes('verified')}
			<FlagAlert
				Icon={BadgeCheck}
				title="Community contribution"
				description="This function's documentation has been verified or corrected by a member of the community."
			/>
		{/if}

		{#if flags.includes('unlisted')}
			<FlagAlert
				Icon={EyeOff}
				title="Unlisted"
				tone="danger"
				description="This function has been unlisted. It is unlikely to be functional and/or useful."
			/>
		{/if}

		{#if flags.includes('Broken')}
			<FlagAlert
				Icon={TriangleAlert}
				title="Broken"
				tone="danger"
				description="This function is recorded as broken. Calling it is unlikely to do what its name suggests."
			/>
		{/if}

		{#if flags.includes('devblock')}
			<FlagAlert
				Icon={SquareCode}
				title="Dev block"
				description="This function is only available inside developer blocks."
			/>
		{/if}
	</div>
{/if}
